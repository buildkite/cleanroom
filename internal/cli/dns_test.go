func TestDNSInstallTrustsLeafCertificateInInvokingUserKeychain(t *testing.T) {
	home := t.TempDir()
	resolverPath := filepath.Join(t.TempDir(), "resolver", exposure.Domain)
	var calls [][]string
	stubDNSInstallEnvironment(t, home, resolverPath, &calls)
	var chownPaths []string
	dnsInstallChown = func(path string, _, _ int) error {
		chownPaths = append(chownPaths, path)
		return nil
	}

	stdout, _ := makeStdoutCapture(t)
	cmd := &DNSCommand{Action: "install"}
	if err := cmd.Run(&runtimeContext{Stdout: stdout}); err != nil {
		t.Fatalf("DNSCommand.Run returned error: %v", err)
	}

	certPath := filepath.Join(home, ".config", "cleanroom", "tls", exposure.LocalCertificateFilename)
	keychain := filepath.Join(home, "Library", "Keychains", "login.keychain-db")
	wantCalls := [][]string{{
		"sudo", "-u", "lachlan", "security", "add-trusted-cert",
		"-r", "trustRoot",
		"-p", "ssl",
		"-k", keychain,
		certPath,
	}}
	if !reflect.DeepEqual(calls, wantCalls) {
		t.Fatalf("unexpected trust commands: got %v want %v", calls, wantCalls)
	}

	certPEM, err := os.ReadFile(certPath)
	if err != nil {
		t.Fatalf("read generated certificate: %v", err)
	}
	block, _ := pemDecodeCertificate(certPEM)
	cert, err := x509.ParseCertificate(block)
	if err != nil {
		t.Fatalf("parse generated certificate: %v", err)
	}
	if cert.IsCA {
		t.Fatal("expected generated exposure certificate not to be a CA")
	}
	if err := cert.VerifyHostname("buildkite." + exposure.Domain); err != nil {
		t.Fatalf("expected generated certificate to verify exposure hostname: %v", err)
	}
	if strings.Contains(strings.Join(calls[0], " "), "System.keychain") {
		t.Fatalf("did not expect install to trust the system keychain: %v", calls[0])
	}

	wantChownPaths := []string{
		filepath.Join(home, ".config"),
		filepath.Join(home, ".config", "cleanroom"),
		filepath.Join(home, ".config", "cleanroom", "tls"),
		certPath,
		filepath.Join(home, ".config", "cleanroom", "tls", exposure.LocalCertificateKeyFilename),
	}
	if !reflect.DeepEqual(chownPaths, wantChownPaths) {
		t.Fatalf("unexpected chown paths: got %v want %v", chownPaths, wantChownPaths)
	}
}

