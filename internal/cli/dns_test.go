func TestResolverFileContent(t *testing.T) {
	t.Parallel()

	content, listen, err := resolverFileContent("127.0.0.1:1153")
	if err != nil {
		t.Fatalf("resolverFileContent returned error: %v", err)
	}
	if got, want := listen, "127.0.0.1:1153"; got != want {
		t.Fatalf("unexpected listen: got %q want %q", got, want)
	}
	for _, want := range []string{
		"# Generated by cleanroom. Do not edit.",
		"nameserver 127.0.0.1",
		"port 1153",
	} {
		if !strings.Contains(content, want) {
			t.Fatalf("expected resolver content to contain %q, got %q", want, content)
		}
	}
	if !resolverFileManaged([]byte(content)) {
		t.Fatal("expected generated resolver file to be managed")
	}
}

