func stubDNSInstallEnvironment(t *testing.T, home, resolverPath string, calls *[][]string) {
	t.Helper()
	prevGOOS := dnsInstallGOOS
	prevEUID := dnsInstallEUID
	prevRunCommand := dnsInstallRunCommand
	prevLookupUser := dnsInstallLookupUser
	prevChown := dnsInstallChown
	prevGetenv := dnsInstallGetenv
	prevUserHomeDir := dnsInstallUserHomeDir
	prevResolverInstallPath := dnsResolverInstallPath
	dnsInstallGOOS = "darwin"
	dnsInstallEUID = func() int { return 0 }
	dnsInstallRunCommand = func(name string, args ...string) error {
		*calls = append(*calls, append([]string{name}, args...))
		return nil
	}
	dnsInstallLookupUser = func(name string) (*user.User, error) {
		return &user.User{Username: name, HomeDir: home}, nil
	}
	dnsInstallChown = func(string, int, int) error {
		return nil
	}
	dnsInstallGetenv = func(key string) string {
		switch key {
		case "SUDO_USER":
			return "lachlan"
		case "SUDO_UID":
			return "501"
		case "SUDO_GID":
			return "20"
		default:
			return ""
		}
	}
	dnsInstallUserHomeDir = func() (string, error) {
		return home, nil
	}
	dnsResolverInstallPath = resolverPath
	t.Cleanup(func() {
		dnsInstallGOOS = prevGOOS
		dnsInstallEUID = prevEUID
		dnsInstallRunCommand = prevRunCommand
		dnsInstallLookupUser = prevLookupUser
		dnsInstallChown = prevChown
		dnsInstallGetenv = prevGetenv
		dnsInstallUserHomeDir = prevUserHomeDir
		dnsResolverInstallPath = prevResolverInstallPath
	})
}

func pemDecodeCertificate(data []byte) ([]byte, bool) {
	block, _ := pem.Decode(data)
	if block == nil || block.Type != "CERTIFICATE" {
		return nil, false
	}
	return block.Bytes, true
}

func readCertificateDNSNames(t *testing.T, certPath string) []string {
	t.Helper()

	certPEM, err := os.ReadFile(certPath)
	if err != nil {
		t.Fatalf("read certificate %s: %v", certPath, err)
	}
	block, ok := pemDecodeCertificate(certPEM)
	if !ok {
		t.Fatalf("decode certificate PEM %s: invalid certificate", certPath)
	}
	cert, err := x509.ParseCertificate(block)
	if err != nil {
		t.Fatalf("parse certificate %s: %v", certPath, err)
	}
	names := append([]string(nil), cert.DNSNames...)
	slices.Sort(names)
	return slices.Compact(names)
}
